export function detectLocale() {
  const saved = document.cookie.split('; ').find((row) => row.startsWith('lng='));
  if (saved) {
    const value = decodeURIComponent(saved.split('=')[1]);
    if (LOCALES.some((l) => l.id === value)) return value;
  }
  const nav = navigator.language || 'pt-BR';
  const exact = LOCALES.find((l) => l.id.toLowerCase() === nav.toLowerCase());
  if (exact) return exact.id;
  const short = nav.slice(0, 2).toLowerCase();
  if (short === 'pt') return 'pt-BR';
  if (short === 'es') return nav.toLowerCase().includes('mx') ? 'es-MX' : 'es';
  if (short === 'fr') return 'fr';
  if (short === 'de') return 'de';
  if (short === 'ja') return 'ja';
  if (short === 'en') return 'en';
  return 'en';
}

export function setLocaleCookie(lng) {
  document.cookie = `lng=${lng}; path=/; max-age=31536000`;
  i18n.changeLanguage(lng);
}

